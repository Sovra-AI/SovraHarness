//! A bounded history of a run for the live chart, and the sums behind the tiles.
//!
//! The whole history is copied into every state snapshot, so it never grows past
//! [`MAX_METRIC_POINTS`]: when full it keeps every other point.

use serde::{Deserialize, Serialize};

/// Most points kept for the chart.
pub const MAX_METRIC_POINTS: usize = 240;
/// Most bytes of generated sample text kept.
pub const MAX_SAMPLE_TEXT_BYTES: usize = 512;

/// One measured moment of a run. Losses are cross entropy in thousandths: lower
/// means better guesses. For display, not a quality promise.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MetricPoint {
    pub round: u32,
    pub loss_milli: u32,
    /// Loss on the held-back text, on the rounds it was measured.
    pub check_loss_milli: Option<u32>,
    pub lr_micro: u32,
    pub tokens_per_second: u32,
}

/// One chart row with no gaps: the check value is the latest one measured.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ChartPoint {
    pub round: u32,
    pub loss_milli: u32,
    pub check_loss_milli: Option<u32>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TrainingMetrics {
    /// Oldest first, at most [`MAX_METRIC_POINTS`].
    pub points: Vec<MetricPoint>,
    /// Time spent training, not counting pauses.
    pub elapsed_ms: u64,
    /// Time left at the recent speed; `None` while it is still being measured.
    pub eta_ms: Option<u64>,
    pub tokens_per_second: u32,
    pub best_check_loss_milli: Option<u32>,
    /// The round that set the best check loss.
    pub best_check_round: u32,
    /// The latest text the model wrote, at most [`MAX_SAMPLE_TEXT_BYTES`].
    pub sample: Option<String>,
    pub sample_round: u32,
}

/// Bytes per second over a stretch of work; zero when no time has passed.
pub fn tokens_per_second(tokens: u64, elapsed_ms: u64) -> u32 {
    if elapsed_ms == 0 {
        return 0;
    }
    u32::try_from(tokens.saturating_mul(1000) / elapsed_ms).unwrap_or(u32::MAX)
}

/// Time left for `remaining_tokens` at this speed; `None` when the speed is not
/// known yet.
pub fn eta_ms(remaining_tokens: u64, tokens_per_second: u32) -> Option<u64> {
    if tokens_per_second == 0 {
        return None;
    }
    Some(remaining_tokens.saturating_mul(1000) / u64::from(tokens_per_second))
}

/// Among how many next letters a model with this loss is, in effect, still
/// choosing: 256 means pure guessing, 1 means certain.
pub fn guess_choices(loss_milli: u32) -> u32 {
    let choices = (f64::from(loss_milli) / 1000.0).exp().round();
    #[expect(
        clippy::cast_possible_truncation,
        clippy::cast_sign_loss,
        reason = "clamped to 1..=256 before the cast"
    )]
    let choices = choices.clamp(1.0, 256.0) as u32;
    choices
}

/// A plain sentence for a loss value.
pub fn guess_quality(loss_milli: u32) -> String {
    match guess_choices(loss_milli) {
        200.. => "Still guessing at random.".to_owned(),
        1 => "Nearly certain of each next letter.".to_owned(),
        choices => format!("Narrowed each next letter down to about {choices} choices."),
    }
}

/// Cuts generated bytes to at most `MAX_SAMPLE_TEXT_BYTES` of displayable text.
/// Bytes that are not valid UTF-8 become the replacement mark, and control
/// characters other than a line break become spaces.
pub fn sample_text(bytes: &[u8]) -> String {
    let mut out = String::new();
    for c in String::from_utf8_lossy(bytes).chars() {
        let c = if c.is_control() && c != '\n' { ' ' } else { c };
        if out.len() + c.len_utf8() > MAX_SAMPLE_TEXT_BYTES {
            break;
        }
        out.push(c);
    }
    out
}

impl TrainingMetrics {
    /// Adds a point, keeping the history bounded and in round order. A point for
    /// the latest round replaces it; an older round is ignored. When the history
    /// is full, every other point is dropped first, always keeping the first and
    /// the latest, so the chart still spans the whole run at half the detail.
    pub fn push(&mut self, point: MetricPoint) {
        match self.points.last_mut() {
            Some(last) if last.round == point.round => {
                // Keep a check value already measured for this round.
                let check = point.check_loss_milli.or(last.check_loss_milli);
                *last = MetricPoint {
                    check_loss_milli: check,
                    ..point
                };
            }
            Some(last) if last.round > point.round => return,
            Some(_) | None => {
                if self.points.len() >= MAX_METRIC_POINTS {
                    self.halve();
                }
                self.points.push(point);
            }
        }
        self.tokens_per_second = point.tokens_per_second;
        if let Some(check) = point.check_loss_milli
            && self.best_check_loss_milli.is_none_or(|best| check < best)
        {
            self.best_check_loss_milli = Some(check);
            self.best_check_round = point.round;
        }
    }

    fn halve(&mut self) {
        let last = self.points.len() - 1;
        let mut carried = None;
        let mut kept = Vec::with_capacity(self.points.len() / 2 + 1);
        for (index, mut point) in std::mem::take(&mut self.points).into_iter().enumerate() {
            // A check value on a dropped point moves to the next kept one, so the
            // check line does not lose its measurements.
            if index == 0 || index == last || index.is_multiple_of(2) {
                point.check_loss_milli = point.check_loss_milli.or(carried.take());
                kept.push(point);
            } else if point.check_loss_milli.is_some() {
                carried = point.check_loss_milli;
            }
        }
        self.points = kept;
    }

    /// Records the time spent so far and works out the time left.
    pub fn observe(&mut self, elapsed_ms: u64, remaining_tokens: u64) {
        self.elapsed_ms = elapsed_ms;
        self.eta_ms = eta_ms(remaining_tokens, self.tokens_per_second);
    }

    /// Keeps the latest text the model wrote.
    pub fn set_sample(&mut self, bytes: &[u8], round: u32) {
        self.sample = Some(sample_text(bytes));
        self.sample_round = round;
    }

    /// Whether the check loss has gone `limit` rounds without improving. Never
    /// true with a limit of zero or before the first check.
    pub fn stalled(&self, round: u32, limit: u32) -> bool {
        limit > 0
            && self.best_check_loss_milli.is_some()
            && round.saturating_sub(self.best_check_round) >= limit
    }

    pub fn latest(&self) -> Option<&MetricPoint> {
        self.points.last()
    }

    /// Rows for the chart. The check line has a value on every row (the latest
    /// one measured, or the first one for rows before it) because the chart cannot
    /// draw gaps; when no check was ever measured every row has `None` and the
    /// chart should draw one line.
    pub fn chart(&self) -> Vec<ChartPoint> {
        let mut check = self.points.iter().find_map(|point| point.check_loss_milli);
        self.points
            .iter()
            .map(|point| {
                check = point.check_loss_milli.or(check);
                ChartPoint {
                    round: point.round,
                    loss_milli: point.loss_milli,
                    check_loss_milli: check,
                }
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn point(round: u32) -> MetricPoint {
        MetricPoint {
            round,
            loss_milli: 5000 - round,
            check_loss_milli: None,
            lr_micro: 3000,
            tokens_per_second: 1000 + round,
        }
    }

    #[test]
    fn history_stays_bounded_ordered_and_spans_the_whole_run() {
        let mut metrics = TrainingMetrics::default();
        for round in 1..=3000 {
            metrics.push(point(round));
            assert!(metrics.points.len() <= MAX_METRIC_POINTS);
            assert_eq!(metrics.points[0].round, 1);
            assert_eq!(metrics.latest().unwrap().round, round);
            assert!(metrics.points.windows(2).all(|w| w[0].round < w[1].round));
        }
        assert!(metrics.points.len() > MAX_METRIC_POINTS / 2);
        assert_eq!(metrics.tokens_per_second, 4000);
        // The first overflow keeps the first, every other, and the latest point.
        let mut metrics = TrainingMetrics::default();
        for round in 1..=241 {
            metrics.push(point(round));
        }
        let rounds: Vec<u32> = metrics.points.iter().map(|p| p.round).collect();
        assert_eq!(rounds.len(), 122);
        assert_eq!(&rounds[..3], &[1, 3, 5]);
        assert_eq!(&rounds[118..], &[237, 239, 240, 241]);
    }

    #[test]
    fn the_same_round_is_replaced_and_an_older_round_is_ignored() {
        let mut metrics = TrainingMetrics::default();
        metrics.push(MetricPoint {
            check_loss_milli: Some(4000),
            ..point(5)
        });
        metrics.push(MetricPoint {
            loss_milli: 1,
            ..point(5)
        });
        assert_eq!(metrics.points.len(), 1);
        assert_eq!(metrics.points[0].loss_milli, 1);
        assert_eq!(metrics.points[0].check_loss_milli, Some(4000));
        metrics.push(point(4));
        assert_eq!(metrics.points.len(), 1);
        assert_eq!(metrics.tokens_per_second, 1005);
    }

    #[test]
    fn the_best_check_and_stall_follow_the_check_line_only() {
        let mut metrics = TrainingMetrics::default();
        assert!(!metrics.stalled(1000, 10));
        metrics.push(point(1));
        assert_eq!(metrics.best_check_loss_milli, None);
        assert!(!metrics.stalled(1000, 10));
        for (round, check) in [(10, 3000), (20, 2500), (30, 2600), (40, 2500)] {
            metrics.push(MetricPoint {
                check_loss_milli: Some(check),
                ..point(round)
            });
        }
        assert_eq!(metrics.best_check_loss_milli, Some(2500));
        assert_eq!(metrics.best_check_round, 20);
        assert!(!metrics.stalled(40, 0));
        assert!(!metrics.stalled(40, 21));
        assert!(metrics.stalled(40, 20));
        assert!(metrics.stalled(41, 20));
        metrics.push(MetricPoint {
            check_loss_milli: Some(2499),
            ..point(50)
        });
        assert_eq!(metrics.best_check_round, 50);
        assert!(!metrics.stalled(60, 20));
    }

    #[test]
    fn halving_keeps_check_measurements_and_the_chart_has_no_gaps() {
        let mut metrics = TrainingMetrics::default();
        assert_eq!(metrics.chart(), []);
        for round in 1..=240 {
            metrics.push(MetricPoint {
                // Only odd indexes (even rounds) carry a check: all would be dropped.
                check_loss_milli: (round % 2 == 0).then_some(9000 - round),
                ..point(round)
            });
        }
        metrics.push(point(241));
        let measured = metrics
            .points
            .iter()
            .filter(|p| p.check_loss_milli.is_some())
            .count();
        assert!(measured >= 119, "{measured}");
        let chart = metrics.chart();
        assert_eq!(chart.len(), metrics.points.len());
        assert!(chart.iter().all(|row| row.check_loss_milli.is_some()));
        // Rows before the first measurement show the first measured value.
        assert_eq!(chart[0].check_loss_milli, Some(9000 - 2));
        assert_eq!(chart[0].round, 1);
        assert_eq!(chart[0].loss_milli, 4999);

        let mut plain = TrainingMetrics::default();
        plain.push(point(1));
        plain.push(point(2));
        assert!(
            plain
                .chart()
                .iter()
                .all(|row| row.check_loss_milli.is_none())
        );
        let mut late = TrainingMetrics::default();
        late.push(point(1));
        late.push(MetricPoint {
            check_loss_milli: Some(7),
            ..point(2)
        });
        late.push(point(3));
        let checks: Vec<_> = late.chart().iter().map(|r| r.check_loss_milli).collect();
        assert_eq!(checks, [Some(7), Some(7), Some(7)]);
    }

    #[test]
    fn speed_and_time_left_are_safe_at_the_edges() {
        assert_eq!(tokens_per_second(0, 0), 0);
        assert_eq!(tokens_per_second(5000, 0), 0);
        assert_eq!(tokens_per_second(5000, 2000), 2500);
        assert_eq!(tokens_per_second(u64::MAX, 1), u32::MAX);
        assert_eq!(eta_ms(10_000, 0), None);
        assert_eq!(eta_ms(10_000, 2500), Some(4000));
        assert_eq!(eta_ms(0, 1), Some(0));
        assert_eq!(eta_ms(u64::MAX, 1), Some(u64::MAX));
        let mut metrics = TrainingMetrics::default();
        metrics.observe(1500, 10_000);
        assert_eq!((metrics.elapsed_ms, metrics.eta_ms), (1500, None));
        metrics.push(point(1500));
        metrics.observe(2500, 10_000);
        assert_eq!((metrics.elapsed_ms, metrics.eta_ms), (2500, Some(4000)));
    }

    #[test]
    fn loss_reads_as_a_number_of_choices() {
        assert_eq!(guess_choices(0), 1);
        assert_eq!(guess_choices(5545), 256);
        assert_eq!(guess_choices(u32::MAX), 256);
        assert_eq!(guess_choices(2303), 10);
        assert_eq!(guess_quality(5545), "Still guessing at random.");
        assert_eq!(guess_quality(100), "Nearly certain of each next letter.");
        assert_eq!(
            guess_quality(2303),
            "Narrowed each next letter down to about 10 choices."
        );
    }

    #[test]
    fn sample_text_is_bounded_displayable_and_never_splits_a_character() {
        assert_eq!(
            sample_text(b"The sun\nwarms\tthe\x00garden"),
            "The sun\nwarms the garden"
        );
        assert_eq!(sample_text(&[b'a', 0xff, b'b']), "a\u{fffd}b");
        let long = "é".repeat(400);
        let cut = sample_text(long.as_bytes());
        assert_eq!(cut.len(), MAX_SAMPLE_TEXT_BYTES);
        assert!(cut.chars().all(|c| c == 'é'));
        let odd = format!("a{long}");
        assert_eq!(sample_text(odd.as_bytes()).len(), MAX_SAMPLE_TEXT_BYTES - 1);
        let mut metrics = TrainingMetrics::default();
        metrics.set_sample(b"garden", 12);
        assert_eq!(metrics.sample.as_deref(), Some("garden"));
        assert_eq!(metrics.sample_round, 12);
        let json = serde_json::to_string(&metrics).unwrap();
        assert_eq!(
            serde_json::from_str::<TrainingMetrics>(&json).unwrap(),
            metrics
        );
    }
}
